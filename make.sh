#!/usr/bin/env bash
# Usage:
#   ./make.sh            build for the current OS
#   ./make.sh win        Windows build: portable .exe in dist/ (plus the NSIS installer when makensis is installed)
#   ./make.sh mac        macOS .app in dist/ (must run on a Mac)
#   ./make.sh all        win, plus mac when running on a Mac
#   ./make.sh dev        run the app in Wails dev mode (hot reload, no full build)
#   ./make.sh test       Go tests, then the frontend typecheck and vitest
#   ./make.sh version    print the app version
#   ./make.sh release <patch|minor|major|X.Y.Z> [-y] [-n]  bump the version, tag and push (starts the GitHub release)
#                        -y skips the confirmation, -n only shows the plan
#   ./make.sh workflow [-w] [branch]  run the Release workflow on GitHub by hand: builds Windows and macOS, publishes nothing
#                        -w waits for it and shows its progress; the branch defaults to the current one
#   ./make.sh clean      remove bin/, dist/, frontend/dist and frontend/node_modules
#   ./make.sh uninstall  quit the app and delete it plus its settings and caches (macOS), for a fresh install
#   ./make.sh makefile   regenerate ./Makefile from the commands in the case block below
# Env: SKIP_TESTS=0 runs the tests before a build.
cd "$(dirname "${BASH_SOURCE[0]:-$0}")" || exit 1

APP=better-docker-desktop-go
NAME="Better Docker Desktop"

# Skip tests for local builds by default; run `SKIP_TESTS=0 ./make.sh` to include them.
export SKIP_TESTS="${SKIP_TESTS:-1}"

case "$(uname -s)" in
    Darwin) HOST=mac ;;
    MINGW*|MSYS*|CYGWIN*) HOST=win ;;
    *) HOST=linux ;;
esac

# Write ./Makefile with one target per label of the case block below, each calling this script.
# Extra arguments pass through: `make uninstall ARGS=...`. The "" label becomes `build`.
gen_makefile() {
    local self; self="$(basename "${BASH_SOURCE[0]:-$0}")"
    awk -v self="$self" '
        /^case "\$1" in/ { incase = 1; next }
        /^esac/           { incase = 0 }
        incase && match($0, /^    ("[^"]*"|[A-Za-z0-9_|-]+)\)/) {
            label = substr($0, 5, RLENGTH - 5)
            n = split(label, names, "|")
            for (i = 1; i <= n; i++) {
                name = names[i]
                if (name == "*") continue
                if (name == "\"\"") name = "build"
                if (!(name in seen)) { seen[name] = 1; order[++count] = name }
            }
        }
        END {
            print "# Generated by ./" self " makefile. Edit the case block there, then rerun it."
            printf ".PHONY:"
            for (i = 1; i <= count; i++) printf " %s", order[i]
            print "\n.DEFAULT_GOAL := build\nARGS ?=\n"
            for (i = 1; i <= count; i++) {
                cmd = (order[i] == "build") ? "" : order[i]
                printf "%s:\n\tbash ./%s %s $(ARGS)\n\n", order[i], self, cmd
            }
        }
    ' "${BASH_SOURCE[0]:-$0}" > Makefile
    echo "Wrote $(pwd)/Makefile"
}

# Put Go, Node and the Wails CLI on PATH even when the shell's PATH lacks them.
find_tools() {
    export PATH="$HOME/go/bin:/c/Program Files/Go/bin:/usr/local/go/bin:/opt/homebrew/bin:/usr/local/bin:$PATH"
    local d
    if ! command -v node >/dev/null; then
        for d in "/c/Program Files/nodejs" "/c/nvm4w/nodejs" "/mnt/c/Program Files/nodejs" "/mnt/c/nvm4w/nodejs"; do
            if [ -x "$d/node" ] || [ -x "$d/node.exe" ]; then PATH="$d:$PATH"; break; fi
        done
    fi
    command -v go >/dev/null || { echo "Go not found. Install it from https://go.dev/dl, then retry." >&2; exit 1; }
    command -v node >/dev/null || { echo "Node.js not found. Install it from https://nodejs.org, then retry." >&2; exit 1; }
    command -v wails3 >/dev/null || { echo "Wails CLI not found. Run: go install github.com/wailsapp/wails/v3/cmd/wails3@latest" >&2; exit 1; }
    echo "Using $(go version | cut -d' ' -f3), node $(node -v), wails3 $(wails3 version 2>/dev/null | head -1)"
}

# On Windows, npm is a bash script whose shebang can resolve to the WSL launcher; use the .cmd shim.
npm_bin() { if [ "$HOST" = win ]; then echo npm.cmd; else echo npm; fi; }

run_tests() {
    echo "==> Running tests"
    go test ./... || return 1
    ( cd frontend && "$(npm_bin)" test )
}

# Install frontend dependencies, and run the tests unless SKIP_TESTS=1.
prepare() {
    find_tools
    echo "==> Installing dependencies"
    ( cd frontend && "$(npm_bin)" install ) || exit 1
    if [ "$SKIP_TESTS" = 1 ]; then
        echo "==> Skipping tests (SKIP_TESTS=1)"
    else
        run_tests || exit 1
    fi
    rm -rf dist && mkdir -p dist
}

build_win() {
    if [ "$HOST" != win ]; then echo "!! Windows builds must run on Windows. Skipping." >&2; return 1; fi
    prepare
    echo "==> Building Windows (portable exe)"
    wails3 build || exit 1
    cp "bin/$APP.exe" "dist/$NAME.exe"
    # The NSIS installer is optional: it needs makensis (https://nsis.sourceforge.io).
    if command -v makensis >/dev/null || [ -x "/c/Program Files (x86)/NSIS/makensis.exe" ]; then
        echo "==> Building the NSIS installer"
        wails3 package && cp bin/*installer*.exe dist/ 2>/dev/null || echo "(installer step failed; the portable exe is still in dist/)"
    else
        echo "(makensis not found: skipping the installer)"
    fi
}

build_mac() {
    if [ "$HOST" != mac ]; then echo "!! macOS builds require running on a Mac. Skipping." >&2; return 1; fi
    prepare
    echo "==> Building macOS (.app)"
    wails3 package || exit 1
    cp -R bin/*.app dist/
}

# The app version lives in build/config.yml (the source of truth), frontend/package.json (and its
# lock file) and the appVersion constant in service.go.
current_version() {
    sed -n 's/^  version: "\([0-9][^"]*\)".*/\1/p' build/config.yml | head -n 1
}

# Bump the version, commit, tag and push; the tag starts the GitHub release workflow.
#   release patch          0.2.0 -> 0.2.1
#   release minor          0.2.0 -> 0.3.0
#   release major          0.2.0 -> 1.0.0
#   release 0.3.0          set an exact version
# Options: -y / --yes skips the confirmation, -n / --dry-run only shows the plan.
release_app() {
    local YES=0 DRY=0 BUMP="" a
    for a in "$@"; do
        case "$a" in
            -y|--yes) YES=1 ;;
            -n|--dry-run) DRY=1 ;;
            -*) echo "Unknown option: $a" >&2; return 2 ;;
            *) BUMP="$a" ;;
        esac
    done
    [ -n "$BUMP" ] || { echo "Usage: $0 release <patch|minor|major|X.Y.Z> [-y] [-n]" >&2; return 2; }

    find_tools >/dev/null || return 1
    git rev-parse --git-dir >/dev/null 2>&1 || { echo "Not a git repository." >&2; return 1; }

    local CURRENT NEXT TAG BRANCH REMOTE=origin
    CURRENT=$(current_version)
    [ -n "$CURRENT" ] || { echo "Could not read the version from build/config.yml." >&2; return 1; }
    NEXT=$(BUMP="$BUMP" CURRENT="$CURRENT" node -e '
        const [a, b, c] = process.env.CURRENT.split(".").map(Number);
        const k = process.env.BUMP;
        const v = k === "patch" ? [a, b, c + 1] : k === "minor" ? [a, b + 1, 0] : k === "major" ? [a + 1, 0, 0] : null;
        if (v) console.log(v.join("."));
        else if (/^\d+\.\d+\.\d+$/.test(k)) console.log(k);
        else { console.error("Version must be patch, minor, major or X.Y.Z"); process.exit(1); }
    ') || return 1
    TAG="v$NEXT"
    BRANCH=$(git symbolic-ref --short -q HEAD || true)

    [ -n "$BRANCH" ] || { echo "Detached HEAD: check out a branch first." >&2; return 1; }
    git remote get-url "$REMOTE" >/dev/null 2>&1 || { echo "No '$REMOTE' remote. Add one first (git remote add origin <url>)." >&2; return 1; }
    [ "$NEXT" != "$CURRENT" ] || { echo "Version is already $CURRENT." >&2; return 1; }
    [ -z "$(git status --porcelain)" ] || { echo "Working tree has uncommitted changes. Commit or stash them first." >&2; git status --short >&2; return 1; }
    if git rev-parse -q --verify "refs/tags/$TAG" >/dev/null; then echo "Tag $TAG already exists locally." >&2; return 1; fi

    echo "==> Checking $REMOTE"
    git fetch --quiet "$REMOTE" "$BRANCH" --tags 2>/dev/null || true
    if git ls-remote --exit-code --tags "$REMOTE" "refs/tags/$TAG" >/dev/null 2>&1; then echo "Tag $TAG already exists on $REMOTE." >&2; return 1; fi
    if git rev-parse -q --verify "$REMOTE/$BRANCH" >/dev/null 2>&1 && [ "$(git rev-list --count "HEAD..$REMOTE/$BRANCH")" != 0 ]; then
        echo "$BRANCH is behind $REMOTE/$BRANCH. Pull first." >&2
        return 1
    fi

    echo
    echo "  Release  $CURRENT -> $NEXT  (tag $TAG)"
    echo "  Branch   $BRANCH  ->  $REMOTE ($(git remote get-url "$REMOTE"))"
    echo "  Updates  build/config.yml, frontend/package.json, frontend/package-lock.json, service.go"
    echo
    if [ "$DRY" = 1 ]; then echo "Dry run: nothing changed."; return 0; fi
    if [ "$YES" != 1 ]; then
        read -r -p "Bump, commit, tag and push? [y/N] " a
        case "$a" in y|Y|yes) ;; *) echo "Cancelled."; return 1 ;; esac
    fi

    # Replace only the app's own version in each file. perl instead of sed because BSD sed (macOS)
    # has no first-match address.
    export NEXT
    perl -0pi -e 's/^(  version: ")[^"]*"/$1$ENV{NEXT}"/m' build/config.yml
    perl -0pi -e 's/^(const appVersion = ")[^"]*"/$1$ENV{NEXT}"/m' service.go
    perl -0pi -e 's/^(  "version": ")[^"]*"/$1$ENV{NEXT}"/m' frontend/package.json
    node -e '
        const fs = require("fs"), f = "frontend/package-lock.json";
        if (!fs.existsSync(f)) process.exit(0);
        const l = JSON.parse(fs.readFileSync(f, "utf8"));
        l.version = process.env.NEXT;
        if (l.packages && l.packages[""]) l.packages[""].version = process.env.NEXT;
        fs.writeFileSync(f, JSON.stringify(l, null, 2) + "\n");
    '

    # Fail before committing if any file did not take the new version.
    local bad=""
    [ "$(current_version)" = "$NEXT" ] || bad="build/config.yml"
    grep -q "^const appVersion = \"$NEXT\"" service.go || bad="service.go"
    [ "$(node -p "require('./frontend/package.json').version")" = "$NEXT" ] || bad="frontend/package.json"
    if [ -n "$bad" ]; then echo "$bad was not updated; restoring." >&2; git checkout -- .; return 1; fi

    git add build/config.yml service.go frontend/package.json
    if [ -f frontend/package-lock.json ]; then git add frontend/package-lock.json; fi
    git commit -m "Release $TAG"
    git tag -a "$TAG" -m "$NAME $TAG"

    echo "==> Pushing $BRANCH and $TAG"
    if ! git push --atomic "$REMOTE" "HEAD:refs/heads/$BRANCH" "refs/tags/$TAG"; then
        echo "Push failed. The commit and tag exist locally. Retry the push, or undo with:" >&2
        echo "  git tag -d $TAG && git reset --hard HEAD~1" >&2
        return 1
    fi

    echo
    echo "Pushed $TAG. The release workflow is building Windows and macOS now."
    echo "Watch it: $(git remote get-url "$REMOTE" | sed -E 's#^git@[^:]+:#https://github.com/#; s#\.git$##')/actions"
}

# Run the Release workflow on GitHub by hand (workflow_dispatch). It builds Windows and macOS and
# attaches the installers to the run; only a version tag publishes a release.
#   workflow               run it on the current branch
#   workflow -w            ...and follow it until it finishes
#   workflow <branch>      run it on another branch (the branch must be pushed)
trigger_workflow() {
    local WATCH=0 REF="" a
    for a in "$@"; do
        case "$a" in
            -w|--watch) WATCH=1 ;;
            -*) echo "Unknown option: $a" >&2; return 2 ;;
            *) REF="$a" ;;
        esac
    done
    command -v gh >/dev/null || { echo "GitHub CLI not found. Install it from https://cli.github.com, then run: gh auth login" >&2; return 1; }
    gh auth status >/dev/null 2>&1 || { echo "Not logged in to GitHub. Run: gh auth login" >&2; return 1; }
    git remote get-url origin >/dev/null 2>&1 || { echo "No 'origin' remote. Add one first (git remote add origin <url>)." >&2; return 1; }

    [ -n "$REF" ] || REF=$(git symbolic-ref --short -q HEAD || true)
    [ -n "$REF" ] || { echo "Detached HEAD: pass a branch name." >&2; return 1; }
    # The workflow runs the code on GitHub, not what is on this disk.
    git fetch --quiet origin "$REF" 2>/dev/null || { echo "Branch '$REF' is not on origin. Push it first." >&2; return 1; }
    if [ "$(git rev-parse -q --verify "$REF" 2>/dev/null)" != "$(git rev-parse -q --verify "origin/$REF" 2>/dev/null)" ]; then
        echo "Note: '$REF' differs from origin/$REF; GitHub builds what is on origin." >&2
    fi
    [ -z "$(git status --porcelain)" ] || echo "Note: uncommitted changes are not part of the build." >&2

    echo "==> Starting the Release workflow on $REF"
    gh workflow run release.yml --ref "$REF" || return 1

    # The run takes a moment to appear in the list.
    local ID="" i
    for i in 1 2 3 4 5 6; do
        sleep 3
        ID=$(gh run list --workflow=release.yml --branch "$REF" --event workflow_dispatch --limit 1 --json databaseId --jq '.[0].databaseId' 2>/dev/null)
        [ -n "$ID" ] && break
    done
    [ -n "$ID" ] || { echo "Started, but could not find the run. Check the Actions tab." >&2; return 0; }
    echo "Run: $(gh run view "$ID" --json url --jq .url)"
    if [ "$WATCH" = 1 ]; then
        gh run watch "$ID" --exit-status || return 1
        echo "Installers are attached to the run under Artifacts."
    fi
}

# Remove the installed app and everything it stored, so the next install starts clean.
# Leaves Docker, kubeconfig and build output (bin/, dist/) alone.
uninstall_app() {
    [ "$(uname -s)" = "Darwin" ] || { echo "uninstall is macOS only" >&2; exit 1; }
    local id="com.rea.betterdockerdesktop" lib="$HOME/Library"
    pkill -x "$NAME" 2>/dev/null || true
    pkill -x "$APP" 2>/dev/null || true
    local paths=(
        "/Applications/$NAME.app" "$HOME/Applications/$NAME.app"
        "$lib/Application Support/$id" "$lib/Application Support/$NAME" "$lib/Application Support/$APP"
        "$lib/Caches/$id" "$lib/Caches/$APP"
        "$lib/WebKit/$id" "$lib/WebKit/$APP"
        "$lib/Preferences/$id.plist" "$lib/Saved Application State/$id.savedState"
        "$lib/HTTPStorages/$id" "$lib/Logs/$id"
    )
    local p
    for p in "${paths[@]}"; do
        if [ -e "$p" ]; then rm -rf "$p" && echo "removed $p"; fi
    done
    echo "Uninstalled $NAME."
}

case "$1" in
    makefile)   gen_makefile ;;
    uninstall)  uninstall_app ;;
    version)    current_version ;;
    release)    shift; release_app "$@" ;;
    workflow)   shift; trigger_workflow "$@" ;;
    win)        build_win && exec "dist/$NAME.exe" ;;
    mac)        build_mac && open "dist/$NAME.app" ;;
    all)
                if [ "$HOST" = win ]; then "$0" win || exit 1; fi
                if [ "$HOST" = mac ]; then "$0" mac || exit 1; fi
    ;;
    dev)        find_tools && ( cd frontend && "$(npm_bin)" install ) && exec wails3 dev ;;
    test)       find_tools && run_tests ;;
    clean)      rm -rf bin dist frontend/dist frontend/node_modules && mkdir -p frontend/dist && touch frontend/dist/.gitkeep && echo "Cleaned." ;;
    "")         if [ "$HOST" = mac ]; then build_mac; else build_win; fi ;;
    *)          echo "Usage: $0 [win|mac|all|dev|test|clean|version|release|workflow|uninstall|makefile]" >&2; exit 2 ;;
esac
